#!/usr/bin/env python3
"""Generate LaTeX declarations from interlinear CSV metadata and active context."""
from __future__ import annotations

import argparse
from pathlib import Path

from context_dump import build
from interlinear_io import load_csv


def escape_tex(value: str) -> str:
    replacements = {
        "\\": r"\textbackslash{}",
        "{": r"\{",
        "}": r"\}",
        "$": r"\$",
        "&": r"\&",
        "#": r"\#",
        "%": r"\%",
        "_": r"\_",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    return "".join(replacements.get(char, char) for char in value).replace("\n", " ")


def translations(row: dict[str, str]) -> str:
    values = []
    for field, value in row.items():
        if not value.strip() or not field.startswith("translation"):
            continue
        language = field.removeprefix("translation_").upper()
        prefix = f"{language}: " if language else ""
        values.append(prefix + value.strip())
    return " | ".join(values)


def lean_summary(row: dict[str, str]) -> str:
    parts = [
        row.get("lean_status", "").strip(),
        row.get("lean_ref", "").strip(),
        row.get("lean_toolchain", "").strip(),
        row.get("lean_note", "").strip(),
    ]
    return "; ".join(part for part in parts if part)


def reference_summary(row: dict[str, str]) -> str:
    parts = []
    confirmed = row.get("stacks_ref", "").strip()
    candidate = row.get("stacks_candidate", "").strip()
    if confirmed:
        parts.append(f"Stacks Tag {confirmed} (checked)")
    if candidate:
        parts.append(f"Stacks Tag {candidate} (candidate; not checked)")
    return "; ".join(parts)


def pdf_hex(value: str) -> str:
    return "FEFF" + value.encode("utf-16-be").hex().upper()


def render(document: Path, data: Path, context_tags: set[str]) -> str:
    _, rows = load_csv(data)
    by_label = {row.get("label", ""): row for row in rows}
    contexts = build(document, data, context_tags)
    lines = ["% Generated by render_latex_data.py; edit the CSV, not this file."]
    for label, record in contexts.items():
        row = by_label.get(label, {})
        explanation = row.get("explanation", "") or row.get("ai_comment", "")
        context = r"\par ".join(
            rf"\texttt{{{escape_tex(item['label'])}}}: {item['text']}"
            for item in record["context"]
        )
        fields = [
            escape_tex(translations(row)),
            escape_tex(explanation),
            context,
            escape_tex(lean_summary(row)),
            escape_tex(reference_summary(row)),
            pdf_hex(
                "; ".join(
                    part for part in (
                        f"Translation: {translations(row)}" if translations(row) else "",
                        f"Explanation: {explanation}" if explanation else "",
                        f"Context: {', '.join(item['label'] for item in record['context'])}"
                        if record["context"] else "",
                        f"Lean: {lean_summary(row)}" if lean_summary(row) else "",
                    )
                    if part
                )
            ),
        ]
        lines.append(
            "\\InterlinearDeclare"
            f"{{{label}}}"
            + "".join(f"{{{value}}}" for value in fields)
        )
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--document", type=Path, required=True)
    parser.add_argument("--data", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument(
        "--context-tags",
        default="definition,theorem,lemma,proposition,hypothesis,setup",
        help="comma-separated tags included as active local context",
    )
    args = parser.parse_args()
    tags = {tag.strip() for tag in args.context_tags.split(",") if tag.strip()}
    output = render(args.document, args.data, tags)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(output, encoding="utf-8")
    count = output.count("\\InterlinearDeclare")
    print(f"Wrote LaTeX metadata for {count} labels")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
