#!/usr/bin/env bash
# Regenerate dev/.claude-plugin/marketplace.json from the real catalog, with the
# name swapped to `aperep-dev` so a locally registered working copy does not
# shadow the git-hosted `aperep`.
#
# dev/plugins is a symlink to ../plugins, so the dev marketplace serves the
# working tree live: edit a SKILL.md, /reload-plugins, no commit needed.
#
# Re-run after adding or removing a plugin; skill edits need nothing.

set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."

python3 - <<'PY'
import json, pathlib
src = json.loads(pathlib.Path(".claude-plugin/marketplace.json").read_text())
src["name"] = "aperep-dev"
src["description"] = "Live working copy of the aperep marketplace. Generated by scripts/dev-marketplace.sh."
out = pathlib.Path("dev/.claude-plugin/marketplace.json")
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(json.dumps(src, indent=2) + "\n")
PY

claude plugin validate ./dev

cat <<'EOF'

Register once:   claude plugin marketplace add "$PWD/dev"
After edits:     claude plugin marketplace update aperep-dev && /reload-plugins
EOF
